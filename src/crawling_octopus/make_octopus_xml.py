#!/usr/bin/env python
"""Generate the MJCF for the octopus: a torso carrying N tendon-driven spiral arms.
Default: 4 arms, each with 3 tendons (3 actuated DOF per arm) that bend it in any direction.

    python make_octopus_xml.py                          # 4 arms at 45/135/225/315 deg -> octopus.xml
    python make_octopus_xml.py --mount-angles 60,120,240,300 --body-radius 0.15
    python make_octopus_xml.py --arms 8
    python make_octopus_xml.py --tendons 2 --bend-axes 1   # the old planar two-tendon arm

Each arm is the same 24-link tapered chain as spiral_robot.xml (same baselink.stl, same scale progression,
same tendon-site layout, same muscle/tendon ranges), so keep baselink.stl next to the XML.

Per arm:
  * every link joins the previous one through TWO hinges (axes x and y), so the arm bends in any direction
    (use --bend-axes 1 for the planar single-hinge arm);
  * --tendons spatial tendons (default 3) run along the arm at equal angles around its axis (120 deg apart);
    each is driven by one muscle actuator (ctrl in [0, 1]); tendon 0 is the "up" side of the arm;
  * the bending hinges are passive springs (stiffness/damping/friction) as on the real arm.
Optional: --yaw adds a servo-driven hinge about the vertical axis at each arm root (one more actuator per arm);
          --joint-actuators adds per-hinge position actuators (simulation only, not realistic for hardware).

Control vector order: [a1_m0, a1_m1, a1_m2, a2_m0, ...]  (with --yaw each arm's block starts with a1_yaw).

Geometry: arm axis = local z, "up" = local +y, local x = sideways. Arm i points outward along mount angle
phi_i (0 deg = world +x, counter-clockwise).
Collision: everything collides with the ground only (links, torso and arms never collide with each other).
NOTE: baselink.stl was designed for two tendon channels; the sim only needs the tendon SITES, but a physical
3-tendon arm needs a link design with three routing channels.
"""
import argparse
import math

R = 0.911774                       # taper ratio between consecutive links
N_LINKS = 24
SPACING0 = 0.045951152             # distance link1 -> link2 (shrinks by R each link)
SITE_R = (0.036394210, 0.034423562)    # radius of the tendon entry / exit sites on the base link
SITE_Z = (0.016795002, 0.042801474)    # height of the entry / exit sites on the base link
J_RANGE = 0.523598776
STIFF0, DAMP0, FRIC0, ARM0 = 0.5, 1.0, 0.05, 0.01
TENDON_RANGE = "0.232041 0.928164"
MUSCLE_LENGTHRANGE = "0.408637 0.925424"


def quat_mul(a, b):
    aw, ax, ay, az = a
    bw, bx, by, bz = b
    return (aw * bw - ax * bx - ay * by - az * bz,
            aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw)


def arm_quat(phi):
    """The single-arm model uses (0.5,0.5,0.5,0.5): local z -> world +x, local y -> world +z.
    Rotate that about world z by phi so the arm points along (cos phi, sin phi)."""
    qz = (math.cos(phi / 2), 0.0, 0.0, math.sin(phi / 2))
    return quat_mul(qz, (0.5, 0.5, 0.5, 0.5))


def f(x):
    return f"{x:.9f}"


class Writer:
    def __init__(self):
        self.lines, self.d = [], 0

    def line(self, s):
        self.lines.append("  " * self.d + s)

    def open(self, s):
        self.line(s)
        self.d += 1

    def close(self, tag):
        self.d -= 1
        self.line(tag)


def tendon_angles(n_tendons):
    return [math.radians(90.0 + 360.0 * j / n_tendons) for j in range(n_tendons)]


def build(a):
    n = a.arms
    if a.mount_angles:
        angles = [float(v) for v in a.mount_angles.split(",")]
        assert len(angles) == n, "--mount-angles must list one angle per arm"
    elif n == 4:
        angles = [45.0, 135.0, 225.0, 315.0]
    else:
        angles = [360.0 * i / n for i in range(n)]
    tang = tendon_angles(a.tendons)
    axes = [("jx", "1 0 0"), ("jy", "0 1 0")][: a.bend_axes]

    W = Writer()
    W.line(f"<!-- generated by make_octopus_xml.py: {n} arms at {angles} deg, {a.tendons} tendons per arm -->")
    W.open('<mujoco model="octopus">')
    W.line('<compiler angle="radian" meshdir="."/>')
    W.line('<option gravity="0 0 -9.81" timestep="0.001" solver="Newton"/>')
    W.open("<default>")
    W.line(f'<geom density="{a.density:g}" friction="1 0.5 0.5" contype="0" conaffinity="1"/>')
    W.line('<joint damping="1.0" armature="0.01"/>')
    W.close("</default>")

    W.open("<asset>")
    for k in range(1, N_LINKS + 1):
        s = 0.001 * R ** (k - 1)
        W.line(f'<mesh name="baselink_{k}" file="{a.mesh}" scale="{f(s)} {f(s)} {f(s)}"/>')
    W.line('<texture name="texplane" type="2d" builtin="checker" rgb1=".2 .3 .4" rgb2=".1 0.15 0.2" '
           'width="512" height="512" mark="cross" markrgb=".8 .8 .8"/>')
    W.line('<material name="matplane" reflectance="0.3" texture="texplane" texrepeat="1 1" texuniform="true"/>')
    W.close("</asset>")

    W.open("<worldbody>")
    W.line('<geom name="ground" type="plane" size="10 10 1" pos="0 0 0" material="matplane" '
           'condim="3" contype="1" conaffinity="1"/>')
    W.line('<light pos="1 0.5 0.7" dir="-1 -0.5 -1" directional="true" castshadow="false" '
           'diffuse="1 1 1" specular="0.3 0.3 0.3"/>')
    W.open('<body name="torso" pos="0 0 0.05">')
    W.line('<freejoint name="root"/>')
    W.line(f'<geom name="torso_geom" type="cylinder" size="{a.body_radius:g} {a.body_half_height:g}" '
           f'mass="{a.body_mass:g}" rgba=".75 .35 .3 1"/>')
    W.line('<site name="imu_body" pos="0 0 0" size="0.005"/>')

    for i, deg in enumerate(angles, start=1):
        phi = math.radians(deg)
        px, py = a.body_radius * math.cos(phi), a.body_radius * math.sin(phi)
        q = arm_quat(phi)
        p = f"a{i}"
        if a.yaw:
            W.open(f'<body name="{p}_mount" pos="{f(px)} {f(py)} 0">')
            W.line(f'<joint name="{p}_yaw" type="hinge" axis="0 0 1" range="{-a.yaw_range:.6f} {a.yaw_range:.6f}" '
                   f'damping="0.1" armature="0.005"/>')
            mi = 0.4 * a.mount_mass * 0.03 ** 2   # solid sphere of radius 3 cm
            W.line(f'<inertial pos="0 0 0" mass="{a.mount_mass:g}" diaginertia="{mi:.3e} {mi:.3e} {mi:.3e}"/>')
            W.line('<geom type="cylinder" size="0.03 0.01" rgba=".4 .4 .4 1" contype="0" conaffinity="0" group="2"/>')
            link1_pos = "0 0 0"
        else:
            link1_pos = f"{f(px)} {f(py)} 0"

        for k in range(1, N_LINKS + 1):
            s = R ** (k - 1)
            if k == 1:
                W.open(f'<body name="{p}_link1" pos="{link1_pos}" quat="{q[0]:.9f} {q[1]:.9f} {q[2]:.9f} {q[3]:.9f}">')
            else:
                W.open(f'<body name="{p}_link{k}" pos="0 0 {f(SPACING0 * R ** (k - 2))}">')
                j = k - 1
                for jname, axis in axes:
                    W.line(f'<joint name="{p}_{jname}{j}" type="hinge" axis="{axis}" '
                           f'range="{-J_RANGE:.9f} {J_RANGE:.9f}" '
                           f'stiffness="{STIFF0 * R ** (2 * (j - 1)) * a.stiffness_scale:.6f}" '
                           f'damping="{DAMP0 * R ** (j - 1) * a.damping_scale:.6f}" '
                           f'frictionloss="{FRIC0 * R ** (2 * (j - 1)) * a.frictionloss_scale:.6f}" '
                           f'armature="{ARM0 * R ** (j - 1):.6f}"/>')
            W.line(f'<geom type="mesh" mesh="baselink_{k}"/>')
            for t, ang in enumerate(tang):
                for e, tag in enumerate("ab"):
                    r = SITE_R[e] * s
                    W.line(f'<site name="{p}_s{k}_t{t}{tag}" pos="{f(r * math.cos(ang))} {f(r * math.sin(ang))} '
                           f'{f(SITE_Z[e] * s)}" size="{0.001 * s:.6f}"/>')
        for _ in range(N_LINKS):
            W.close("</body>")
        if a.yaw:
            W.close("</body>")

    W.close("</body>")    # torso
    W.close("</worldbody>")

    W.open("<tendon>")
    for i in range(1, n + 1):
        for t in range(a.tendons):
            W.open(f'<spatial name="a{i}_t{t}" width="0.0007" frictionloss="0.1" rgba=".95 .3 .3 1" '
                   f'limited="true" range="{TENDON_RANGE}">')
            for k in range(1, N_LINKS + 1):
                W.line(f'<site site="a{i}_s{k}_t{t}a"/>')
                W.line(f'<site site="a{i}_s{k}_t{t}b"/>')
            W.close("</spatial>")
    W.close("</tendon>")

    W.open("<actuator>")
    for i in range(1, n + 1):
        if a.yaw:
            W.line(f'<position name="a{i}_yaw_act" joint="a{i}_yaw" kp="{a.yaw_kp:g}" kv="{a.yaw_kv:g}" '
                   f'ctrlrange="{-a.yaw_range:.6f} {a.yaw_range:.6f}" forcerange="{-a.yaw_force:g} {a.yaw_force:g}"/>')
        for t in range(a.tendons):
            W.line(f'<muscle name="a{i}_m{t}" tendon="a{i}_t{t}" ctrllimited="true" ctrlrange="0 1" '
                   f'force="{a.force:g}" lengthrange="{MUSCLE_LENGTHRANGE}"/>')
    if a.joint_actuators:
        for i in range(1, n + 1):
            for j in range(1, N_LINKS):
                for jname, _ in axes:
                    W.line(f'<position name="a{i}_adj_{jname}{j}" joint="a{i}_{jname}{j}" kp="10" '
                           f'ctrlrange="-0.523599 0.523599" forcerange="-1 1"/>')
    W.close("</actuator>")

    W.open("<sensor>")
    W.line('<framequat name="body_quat" objtype="site" objname="imu_body"/>')
    W.line('<gyro name="body_gyro" site="imu_body"/>')
    W.line('<accelerometer name="body_acc" site="imu_body"/>')
    for i in range(1, n + 1):
        if a.yaw:
            W.line(f'<jointpos name="a{i}_yaw_pos" joint="a{i}_yaw"/>')
        for t in range(a.tendons):
            W.line(f'<tendonpos name="a{i}_t{t}_len" tendon="a{i}_t{t}"/>')
    W.close("</sensor>")
    W.close("</mujoco>")
    return "\n".join(W.lines) + "\n", angles


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="octopus.xml")
    ap.add_argument("--mesh", default="baselink.stl")
    ap.add_argument("--arms", type=int, default=4)
    ap.add_argument("--mount-angles", default=None, help="comma-separated degrees, one per arm")
    ap.add_argument("--tendons", type=int, default=3, help="tendons per arm, equally spaced around the axis")
    ap.add_argument("--bend-axes", type=int, choices=[1, 2], default=2,
                    help="hinges per link: 2 = bends in any direction (needed for 3 tendons), 1 = planar")
    ap.add_argument("--body-radius", type=float, default=0.12, help="torso cylinder radius (m); arms mount on this circle")
    ap.add_argument("--body-half-height", type=float, default=0.045, help="torso cylinder half height (m)")
    ap.add_argument("--body-mass", type=float, default=1.5,
                    help="torso mass incl. electronics, battery and servo bodies (kg)")
    ap.add_argument("--density", type=float, default=1100.0, help="arm link density (kg/m^3)")
    ap.add_argument("--force", type=float, default=30.0, help="muscle peak force (N)")
    ap.add_argument("--stiffness-scale", type=float, default=0.3)
    ap.add_argument("--damping-scale", type=float, default=0.5)
    ap.add_argument("--frictionloss-scale", type=float, default=0.3)
    ap.add_argument("--yaw", action="store_true", help="add a servo-driven yaw hinge at each arm root")
    ap.add_argument("--mount-mass", type=float, default=0.05, help="yaw servo mass at each arm root (kg), with --yaw")
    ap.add_argument("--yaw-range-deg", type=float, default=35.0)
    ap.add_argument("--yaw-kp", type=float, default=20.0)
    ap.add_argument("--yaw-kv", type=float, default=1.0)
    ap.add_argument("--yaw-force", type=float, default=3.0, help="max yaw servo torque (N*m)")
    ap.add_argument("--joint-actuators", action="store_true",
                    help="also add per-hinge position actuators on every arm (simulation only)")
    a = ap.parse_args()
    a.yaw_range = math.radians(a.yaw_range_deg)
    if a.tendons >= 3 and a.bend_axes == 1:
        print("warning: 3+ tendons with a single bending axis cannot steer the arm sideways; use --bend-axes 2")

    xml, angles = build(a)
    with open(a.out, "w") as fh:
        fh.write(xml)
    n_act = a.arms * (a.tendons + int(a.yaw))
    n_bodies = 2 + a.arms * (N_LINKS + int(a.yaw))
    n_hinges = a.arms * (N_LINKS - 1) * a.bend_axes + a.arms * int(a.yaw)
    print(f"wrote {a.out}: {a.arms} arms at {angles} deg, {a.tendons} tendons per arm, {a.bend_axes} bend axis/axes per link")
    print(f"expected: bodies={n_bodies}, tendons={a.arms * a.tendons}, hinge dofs={n_hinges}, "
          f"actuators={n_act + (a.arms * (N_LINKS - 1) * a.bend_axes if a.joint_actuators else 0)}")
    print(f"needs {a.mesh} next to the XML (meshdir='.').")


if __name__ == "__main__":
    main()